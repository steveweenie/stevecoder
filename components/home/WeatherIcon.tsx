import type { WeatherIcon as Kind } from "@/lib/feeds";

const CLOUD = ["...###...", "..#####..", ".#######.", "#########", ".#######."];

/** 9x9 pixel sprites, "#" = lit pixel. */
const SPRITES: Record<Kind, string[]> = {
  sun: ["....#....", ".#.....#.", "...###...", "..#####..", "#.#####.#", "..#####..", "...###...", ".#.....#.", "....#...."],
  moon: ["..####...", ".##......", "##.......", "##.......", "##.......", "##.......", "###....#.", ".#######.", "..#####.."],
  partly: ["......#..", "....#...#", ".....###.", "..###.##.", ".#####...", "#######..", "#######..", ".#####...", "........."],
  cloud: [".........", ".........", ...CLOUD, "#########", "........."],
  fog: [".........", "#######..", ".........", "..#######", ".........", "#######..", ".........", "..#######", "........."],
  rain: [...CLOUD, ".........", ".#..#..#.", "#..#..#..", "........."],
  snow: [...CLOUD, ".........", ".#..#..#.", ".........", "..#..#..#"],
  storm: [...CLOUD, "....##...", "...##....", "....##...", "...#....."],
};

export function WeatherIcon({ kind, size = 12 }: { kind: Kind; size?: number }) {
  return (
    <svg width={size} height={size} viewBox="0 0 9 9" shapeRendering="crispEdges" fill="currentColor" aria-hidden="true">
      {SPRITES[kind].flatMap((row, y) =>
        [...row].map((c, x) => (c === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} /> : null)),
      )}
    </svg>
  );
}
